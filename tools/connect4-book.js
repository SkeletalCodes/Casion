/* Turns the output of tools/connect4-book.c into connect-bot/connect-book.js.
   Usage: node tools/connect4-book.js /tmp/book.txt */
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node tools/connect4-book.js <book.txt>'); process.exit(1); }
const book = new Map();
for (const line of fs.readFileSync(src, 'utf8').split('\n')) {
  const m = line.trim().match(/^([0-9a-z]+) ([0-6])$/);
  if (!m) continue;
  if (book.has(m[1])) {
    // a symmetric position can come out as either of two mirror-image moves; both are equal
    if (book.get(m[1]) !== m[2] && +book.get(m[1]) + +m[2] !== 6) throw new Error('conflicting entries for ' + m[1]);
    continue;
  }
  book.set(m[1], m[2]);
}
const keys = [...book.keys()].sort((a, b) => parseInt(a, 36) - parseInt(b, 36));
// each entry is the position key (base 36) followed by the column digit
const data = keys.map((k) => k + book.get(k)).join(',');
const out = `/* Opening book for the 7×6 Connect 4 bot: ${keys.length} positions. Generated by
   tools/connect4-book.c + tools/connect4-book.js; do not edit by hand. Each entry is a position key
   (base 36, see C4.bookKey in connect-ai.js) followed by the column the bot plays (0-6). */
(function () {
  'use strict';
  const book = {};
  '${data}'.split(',').forEach((e) => { book[e.slice(0, -1)] = +e.slice(-1); });
  if (typeof module === 'object' && module.exports) module.exports = book;
  else self.CONNECT_BOOK = book;
})();
`;
const dest = path.join(__dirname, '..', 'connect-bot', 'connect-book.js');
fs.writeFileSync(dest, out);
console.log(`${keys.length} positions → ${path.relative(process.cwd(), dest)} (${(out.length / 1024).toFixed(1)} KB)`);
